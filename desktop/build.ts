// Builds the standalone executable.
//   bun desktop/build.ts            -> dist-desktop/osu-render.exe (Windows x64)
//   bun desktop/build.ts --linux    -> dist-desktop/osu-render-linux (for local testing)
// Steps: Vite build of the web app, generate an embed list of web/dist, compile with Bun.

import { mkdirSync, readdirSync, statSync, writeFileSync, copyFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { $ } from 'bun';

const root = resolve(import.meta.dir, '..');
const dist = join(root, 'web', 'dist');
const out = join(root, 'dist-desktop');
const linux = process.argv.includes('--linux');

console.log('1/3 Building web app');
await $`npm run build --workspace web`.cwd(root);

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

console.log('2/3 Generating embed list');
const entries = walk(dist).map((abs) => {
  const rel = relative(dist, abs).split(sep).join('/');
  return { url: '/' + rel, abs };
});
const lines = entries.map((e, i) => {
  const rel = relative(join(root, 'desktop', 'src'), e.abs).split(sep).join('/');
  return `import f${i} from ${JSON.stringify(rel.startsWith('.') ? rel : './' + rel)} with { type: 'file' };`;
});
const map = entries.map((e, i) => `  ${JSON.stringify(e.url)}: f${i},`).join('\n');
mkdirSync(join(root, 'desktop', 'src'), { recursive: true });
writeFileSync(
  join(root, 'desktop', 'src', 'embedded.gen.ts'),
  `// Generated by desktop/build.ts. Do not edit.\n${lines.join('\n')}\n\nexport const files: Record<string, string> = {\n${map}\n};\n`,
);

console.log('3/3 Compiling ' + (linux ? 'Linux' : 'Windows x64') + ' executable');
mkdirSync(out, { recursive: true });
const outfile = join(out, linux ? 'osu-render-linux' : 'osu-render.exe');
const result = await Bun.build({
  entrypoints: [join(root, 'desktop', 'src', 'main.ts')],
  compile: { target: linux ? 'bun-linux-x64' : 'bun-windows-x64', outfile },
  minify: true,
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
copyFileSync(join(root, 'desktop', 'osu-render.env.example'), join(out, 'osu-render.env.example'));
console.log('Done: ' + outfile);
